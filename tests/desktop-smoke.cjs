const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const project = path.resolve(__dirname,'..');
const out=process.env.CHATHUB_TEST_OUTPUT||path.join(project,'artifacts','validation');
fs.mkdirSync(out,{recursive:true});
async function main() {
  const start = Date.now();
  const env = {...process.env, CHATHUB_SMOKE_PROFILE: path.join(project,'artifacts','test-profiles','desktop-'+process.pid)}; delete env.ELECTRON_RUN_AS_NODE;
  let app, profile;
  const checks=[];
  const launch = async () => {
    app = await electron.launch({executablePath:process.env.CHATHUB_TEST_EXECUTABLE||require('electron'),args:[...(process.env.CHATHUB_TEST_EXECUTABLE?[]:[project]),'--smoke-test'],env,timeout:30000});
    const page=await app.firstWindow(); await page.waitForFunction(()=>document.querySelector('#onboarding-cards').children.length===3 && !!window.chatHub);
    profile=await app.evaluate(({app})=>app.getPath('userData'));
    return page;
  };
  try {
    let page=await launch(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    const bootMs=Date.now()-start;
    const runtime=await page.evaluate(()=>window.chatHub.request('test-runtime'));
    assert.equal(runtime.data.streaming,true);assert.equal(runtime.data.encrypted,true);checks.push('YouTube gRPC module, protocol definition and Windows encryption resolve correctly');
    await app.evaluate(async({session})=>{for(const provider of ['twitch','kick'])await session.fromPartition('persist:chathub-'+provider).protocol.handle('https',()=>new Response('<!doctype html><title>Official chat fixture</title><p>Local native chat fixture, not a signed-in account</p>'));});
    await page.screenshot({path:path.join(out,'ChatHub-welcome.png')});
    assert.equal(await page.locator('#empty-state').isVisible(),true); checks.push('First run: no sample messages or fake live connection');
    assert.equal(await page.locator('.sidebar').isVisible(),false);assert.equal(await page.locator('.titlebar').isVisible(),false);
    assert.equal(await page.locator('.workspace-toolbar').isVisible(),false);assert.equal(await page.locator('.page-heading').isVisible(),false);
    checks.push('Chat-only window: no sidebar, title bar, dashboard, toolbar or visible app buttons');
    await page.keyboard.press('Control+Shift+P');
    await page.waitForFunction(()=>document.querySelectorAll('.chat-column').length===3);
    assert.equal(await page.locator('.chat-column').count(),3); assert.equal(await page.locator('.chat-message').count(),32);
    assert.equal(await page.locator('[data-composer="twitch"] input').isDisabled(),true);
    await page.screenshot({path:path.join(out,'ChatHub-three-chats-preview.png')});
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].webContents.send('hub:event',{type:'command',command:'preview-count',count:2}));
    await page.waitForFunction(()=>document.querySelectorAll('.chat-column').length===2);
    let widths=await page.locator('.chat-column').evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().width)); assert.ok(Math.abs(widths[0]-widths[1])<=1);
    await page.screenshot({path:path.join(out,'ChatHub-two-chats-preview.png')});
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].webContents.send('hub:event',{type:'command',command:'preview-count',count:1}));
    await page.waitForFunction(()=>document.querySelectorAll('.chat-column').length===1);
    await page.screenshot({path:path.join(out,'ChatHub-one-chat-preview.png')});
    checks.push('One full-width, two equal halves, three equal columns; explicit preview and disabled sending');
    await page.keyboard.press('Control+Shift+P');
    await page.keyboard.press('Control+Shift+C');
    await page.locator('#connections-dialog').waitFor({state:'visible'});
    const yt=page.locator('[data-connection="youtube"]');
    await yt.locator('input').fill('https://evil.example/watch?v=abcdefghijk');await yt.locator('[type="submit"]').click();
    await yt.locator('.connection-result').filter({hasText:'youtube.com'}).waitFor();
    await yt.locator('input').fill('https://www.youtube.com/@Ty0x7');await yt.locator('[type="submit"]').click();
    await page.waitForFunction(()=>document.querySelectorAll('.chat-column').length===1);
    await page.locator('[data-connection="twitch"] input').fill('sample_creator');await page.locator('[data-connection="twitch"] [type="submit"]').click();
    await page.waitForFunction(()=>document.querySelectorAll('.chat-column').length===2);
    checks.push('Configuration accepts YouTube channel URL, rejects foreign URLs, and defaults Twitch to official chat');
    await page.locator('[data-connection="kick"] input').fill('sample_creator');await page.locator('[data-connection="kick"] [type="submit"]').click();
    await page.locator('#connections-dialog .close-dialog').click();
    await page.waitForFunction(()=>document.querySelectorAll('.chat-column').length===3 && document.querySelector('.column-status.native'));
    await page.waitForTimeout(300);
    let native=await app.evaluate(({BrowserWindow})=>{const v=BrowserWindow.getAllWindows()[0].contentView.children.at(-1);return{bounds:v.getBounds(),visible:v.getVisible(),preferences:v.webContents.getLastWebPreferences()};});
    assert.equal(native.visible,true);assert.ok(native.bounds.width>200);assert.equal(native.preferences.sandbox,true);assert.equal(native.preferences.nodeIntegration,false);assert.equal(native.preferences.contextIsolation,true);assert.equal(native.preferences.preload,undefined);
    await page.keyboard.press('Control+,');await page.waitForTimeout(100);
    assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].contentView.children.at(-1).getVisible()),false);
    await page.locator('#setting-name').fill('Evening studio');await page.locator('#setting-font').selectOption('16');await page.locator('#setting-compact').check();
    await page.locator('#settings-form [type="submit"]').click();await page.locator('#settings-result').filter({hasText:'Saved'}).waitFor();
    assert.equal(await page.locator('#workspace-name').textContent(),'Evening studio');
    const vault=await page.evaluate(()=>window.chatHub.request('settings',{clients:{twitch:'',youtube:''},googleSecret:'fixture-secret-never-a-real-credential'}));
    assert.equal(vault.ok,true);assert.equal(vault.data.hasGoogleSecret,true);
    const encrypted=fs.readFileSync(path.join(profile,'credentials.json'),'utf8');assert.equal(encrypted.includes('fixture-secret'),false);
    checks.push('Windows credential encryption saves no plaintext secret to disk');
    await page.locator('#settings-dialog .close-dialog').click();await page.waitForTimeout(100);
    assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].contentView.children.at(-1).getVisible()),true);
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1100,750));await page.waitForTimeout(150);
    native=await app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0],v=w.contentView.children.at(-1);return{bounds:v.getBounds(),size:w.getContentSize()};});
    assert.ok(native.bounds.x+native.bounds.width<=native.size[0]);assert.ok(native.bounds.y+native.bounds.height<=native.size[1]);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
    checks.push('Independent Twitch and Kick native views: alignment, resize containment, hide behind dialogs, restore afterward (local fixtures)');
    await page.keyboard.press('Control+Shift+C');
    await page.locator('[data-connection="kick"] [data-move="-1"]').click();
    const saved=JSON.parse(fs.readFileSync(path.join(profile,'workspace.json'),'utf8'));
    assert.deepEqual(saved.rooms.map(r=>r.provider),['youtube','kick','twitch']);assert.equal(saved.name,'Evening studio');assert.equal(saved.settings.fontSize,16);
    await page.locator('[data-connection="kick"] [data-visible]').click();
    assert.equal(await app.evaluate(({webContents})=>webContents.getAllWebContents().filter(w=>w.getURL().includes('kick.com')).length),0);
    checks.push('Saved workspace name, font size, spacing, column order; hidden Kick renderer destroyed');
    assert.equal(errors.length,0,errors.join('\n'));
    const metrics=await app.evaluate(({app})=>app.getAppMetrics().map(p=>({type:p.type,memory:p.memory.workingSetSize})));
    await page.locator('#connections-dialog .close-dialog').click();
    await app.close();app=null;
    page=await launch();
    await page.waitForFunction(()=>document.querySelector('#workspace-name').textContent==='Evening studio');
    assert.equal(await page.locator('.chat-column').count(),2);
    const restored=await page.evaluate(()=>window.chatHub.request('state'));
    assert.deepEqual(restored.data.state.rooms.map(r=>r.provider),['youtube','kick','twitch']);
    assert.equal(restored.data.state.settings.fontSize,16);
    assert.equal(restored.data.state.rooms.find(r=>r.provider==='kick').visible,false);
    checks.push('Full application restart restores workspace name, channel identities, hidden state, order and font settings');
    await app.close();app=null;
    const result={date:new Date().toISOString(),packagedExecutable:!!process.env.CHATHUB_TEST_EXECUTABLE,runtime:require('electron/package.json').version,checks,startupMs:bootMs,processWorkingSetKB:metrics,rendererErrors:errors,liveProviderVerification:false};
    fs.writeFileSync(path.join(out,'desktop-validation.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result,null,2));
  } finally { if(app)await app.close(); }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
